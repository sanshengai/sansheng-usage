import * as fs from 'fs';
import * as path from 'path';
import * as os from 'os';

// Where the wrapper and its forwarding config live, alongside Claude Code's config.
// baseDir is a parameter (default ~/.claude) only so the installer can be tested
// against a scratch directory instead of the real Claude Code config.
const DEFAULT_CLAUDE_DIR = path.join(os.homedir(), '.claude');

interface BridgePaths {
  claudeDir: string;
  wrapper: string;
  forwardConfig: string;
  settings: string;
}
function bridgePaths(baseDir: string): BridgePaths {
  return {
    claudeDir: baseDir,
    wrapper: path.join(baseDir, 'clusage-statusline-bridge.cjs'),
    forwardConfig: path.join(baseDir, 'clusage-bridge-forward.json'),
    settings: path.join(baseDir, 'settings.json'),
  };
}

// The statusline command clusage installs. Runs the wrapper through node.
function wrapperCommand(wrapperPath: string): string {
  return `node "${wrapperPath}"`;
}

// The wrapper Claude Code runs as its statusline command every turn. It caches the
// rate-limit / cost / context fields the extension wants, then forwards stdin to the
// user's previous statusline command (if any) and passes its stdout through, so an
// existing statusline keeps rendering untouched. Pure Node, no dependencies.
const WRAPPER_SOURCE = `// Generated by the clusage VS Code extension. Safe to delete; reinstall from the
// command palette ("clusage: Install statusline bridge"). Caches Claude Code's
// statusline data for the extension, then forwards to any previous statusline.
const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', d => { input += d; });
process.stdin.on('end', () => {
  try {
    const j = JSON.parse(input);
    const rl = j.rate_limits || {};
    const fh = rl.five_hour, sd = rl.seven_day;
    const bridge = {
      writtenAt: Date.now(),
      fiveHour: fh ? { pct: fh.used_percentage, resetAt: fh.resets_at } : null,
      sevenDay: sd ? { pct: sd.used_percentage, resetAt: sd.resets_at } : null,
      cost: j.cost ? j.cost.total_cost_usd : null,
      contextPct: j.context_window ? j.context_window.used_percentage : null,
      model: j.model ? j.model.display_name : null,
    };
    // Only write when the rate_limits field is present (Pro/Max, after first
    // response); otherwise leave any prior reading in place rather than blanking it.
    if (fh || sd) {
      const outPath = process.env.CLUSAGE_BRIDGE_OUT || path.join(os.homedir(), '.claude', 'clusage-bridge.json');
      fs.writeFileSync(outPath, JSON.stringify(bridge));
    }
  } catch (e) { /* never let caching break the statusline */ }

  // Forward to the user's previous statusline command, if one was captured.
  try {
    const cfgPath = process.env.CLUSAGE_FORWARD_CFG || path.join(os.homedir(), '.claude', 'clusage-bridge-forward.json');
    const forward = JSON.parse(fs.readFileSync(cfgPath, 'utf8')).command;
    if (forward) {
      const r = spawnSync(forward, { input, shell: true, encoding: 'utf8' });
      if (r.stdout) process.stdout.write(r.stdout);
    }
  } catch (e) { /* no forward configured, or it failed — statusline just shows nothing */ }
});
`;

export interface InstallResult {
  ok: boolean;
  message: string;
}

function readJson(file: string): any | null {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

/**
 * Install the statusline bridge: write the wrapper, capture whatever statusline the
 * user already has so it keeps working, and repoint Claude Code's statusLine at the
 * wrapper. Idempotent — re-running when already installed just refreshes the wrapper.
 *
 * Claude Code's statusLine lives in ~/.claude/settings.json (not VS Code settings),
 * so this edits that file directly, after backing it up.
 */
export function installStatuslineBridge(baseDir: string = DEFAULT_CLAUDE_DIR): InstallResult {
  const P = bridgePaths(baseDir);
  try {
    fs.mkdirSync(P.claudeDir, { recursive: true });
  } catch {
    return { ok: false, message: `无法创建 ${P.claudeDir}` };
  }

  // Claude Code settings must be strict JSON. If it exists but won't parse, don't
  // guess — tell the user to wire it up by hand rather than corrupt their config.
  let settings: any = {};
  if (fs.existsSync(P.settings)) {
    settings = readJson(P.settings);
    if (settings === null) {
      return {
        ok: false,
        message: `${P.settings} 无法解析为 JSON，未改动。请手动把 statusLine.command 设为：${wrapperCommand(P.wrapper)}`,
      };
    }
  }

  const current = settings.statusLine;
  const alreadyOurs =
    current && typeof current.command === 'string' && current.command.includes('clusage-statusline-bridge');

  // Capture the command to forward to — but never capture our own wrapper (that would
  // make it call itself). Re-installing preserves the forward already on file.
  let forwardCommand: string | null = null;
  if (current && current.type === 'command' && typeof current.command === 'string' && !alreadyOurs) {
    forwardCommand = current.command;
  } else if (alreadyOurs) {
    forwardCommand = readJson(P.forwardConfig)?.command ?? null;
  }

  // Write the wrapper and its forward config.
  try {
    fs.writeFileSync(P.wrapper, WRAPPER_SOURCE);
    fs.writeFileSync(P.forwardConfig, JSON.stringify({ command: forwardCommand }, null, 2));
  } catch (e) {
    return { ok: false, message: `写入桥脚本失败：${e instanceof Error ? e.message : String(e)}` };
  }

  // Back up settings.json before touching it, then repoint statusLine at the wrapper,
  // preserving any padding the user had set and every other key in the file.
  try {
    if (fs.existsSync(P.settings)) {
      fs.copyFileSync(P.settings, P.settings + '.clusage-bak');
    }
    settings.statusLine = {
      type: 'command',
      command: wrapperCommand(P.wrapper),
      ...(current && typeof current.padding === 'number' ? { padding: current.padding } : {}),
    };
    fs.writeFileSync(P.settings, JSON.stringify(settings, null, 2));
  } catch (e) {
    return { ok: false, message: `更新 ${P.settings} 失败：${e instanceof Error ? e.message : String(e)}` };
  }

  const forwardNote = forwardCommand
    ? `已保留你原有的 statusline（${forwardCommand}）并继续转发给它。`
    : `未检测到已有 statusline，桥只负责给扩展供数据。`;
  return {
    ok: true,
    message: `statusline 桥已安装。${forwardNote} 新开的 Claude Code 会话即可让扩展零请求读取额度（旧会话需重启生效）。`,
  };
}
